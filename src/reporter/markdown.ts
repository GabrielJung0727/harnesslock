import type { DriftEvent, ReportSection, VerificationReport } from "../types/model.js";
import { VERSION } from "../version.js";

const SECTION_NAMES: Record<ReportSection, string> = {
  lock: "Lockfile",
  agents: "Agents",
  instructions: "Instructions",
  mcp: "MCP Servers",
  skills: "Skills",
  hooks: "Hooks",
  rules: "Rules",
  security: "Security",
};

function escapeCell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function severityBadge(event: DriftEvent): string {
  return event.severity === "error" ? "❌ error" : event.severity === "warning" ? "⚠️ warning" : "ℹ️ info";
}

/** GitHub PR comment / job summary. */
export function renderMarkdown(report: VerificationReport): string {
  const { errors, warnings } = report.summary;
  const passed = errors === 0;
  const lines: string[] = [];
  lines.push(`## 🔒 HarnessLock — ${passed ? "✅ Verification passed" : "❌ Agent configuration drift detected"}`);
  lines.push("");
  lines.push(
    `**${errors}** error${errors === 1 ? "" : "s"} · **${warnings}** warning${warnings === 1 ? "" : "s"} · ` +
      `mode \`${report.mode}\` · instructions \`${report.instructionStrategy}\` · ${report.durationMs}ms`,
  );
  lines.push("");

  const sections = Object.keys(SECTION_NAMES) as ReportSection[];
  lines.push("| Section | Verified | Issues |", "| --- | ---: | ---: |");
  for (const section of sections) {
    const ok = report.components.filter((c) => c.section === section && c.state === "ok").length;
    const issues = report.events.filter((e) => e.section === section).length;
    if (ok === 0 && issues === 0) continue;
    lines.push(`| ${SECTION_NAMES[section]} | ${ok} | ${issues === 0 ? "0" : `**${issues}**`} |`);
  }
  lines.push("");

  if (report.events.length > 0) {
    lines.push("### Findings", "");
    lines.push("| Severity | Section | Component | Finding | Location |", "| --- | --- | --- | --- | --- |");
    for (const event of report.events) {
      const location = event.file ? `\`${event.file}${event.line ? `:${event.line}` : ""}\`` : "";
      lines.push(
        `| ${severityBadge(event)} | ${SECTION_NAMES[event.section]} | \`${escapeCell(event.componentId)}\` | ${escapeCell(event.message)} | ${location} |`,
      );
    }
    lines.push("");

    const detailed = report.events.filter((e) => e.expected !== undefined || e.actual !== undefined);
    if (detailed.length > 0) {
      lines.push("<details><summary>Expected vs actual</summary>", "");
      for (const event of detailed) {
        lines.push(`- **${escapeCell(event.componentId)}** — ${escapeCell(event.message)}`);
        if (event.expected !== undefined) lines.push(`  - expected: \`${escapeCell(event.expected)}\``);
        if (event.actual !== undefined) lines.push(`  - actual: \`${escapeCell(event.actual)}\``);
      }
      lines.push("", "</details>", "");
    }

    const remediations = [...new Set(report.events.map((e) => e.remediation).filter((r): r is string => Boolean(r)))];
    if (remediations.length > 0) {
      lines.push("### 💡 Remediation", "");
      for (const remediation of remediations) {
        lines.push(remediation.startsWith("npx ") ? `- \`${remediation}\`` : `- ${remediation}`);
      }
      lines.push("");
    }
  }

  lines.push(`<sub>Generated by HarnessLock v${VERSION} — static, deterministic, no secrets stored.</sub>`);
  return `${lines.join("\n")}\n`;
}
