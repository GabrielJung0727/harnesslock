import { parse as parseYaml, stringify as stringifyYaml } from "yaml";
import { z } from "zod";
import { ConfigValidationError, formatZodIssues } from "./config-schema.js";

const fingerprintSchema = z.string().regex(/^sha256:[0-9a-f]{64}$/, "must be a sha256:<hex> fingerprint");
const agentIdSchema = z.enum(["claude-code", "codex", "cursor"]);
const stringList = z.array(z.string());

const lockMcpSchema = z.object({
  sourceType: z.enum(["npm", "uvx", "docker", "local", "http"]),
  package: z.string().optional(),
  requestedVersion: z.string().optional(),
  resolvedVersion: z.string().optional(),
  resolvedFrom: z.string().optional(),
  definedIn: stringList,
  pinnedInConfigs: stringList,
  requiredEnv: z
    .record(z.string(), z.object({ required: z.boolean(), value: z.literal("excluded") }))
    .optional(),
  permissions: z.object({ allowed: stringList }),
  configFingerprint: fingerprintSchema,
  configFingerprints: z.record(z.string(), fingerprintSchema),
});

export const lockSchema = z.object({
  lockVersion: z.literal(1),
  generatedAt: z.string(),
  generator: z.string().optional(),
  specHash: fingerprintSchema,
  agents: z
    .record(z.string(), z.object({ requested: z.string().optional(), presence: z.enum(["required", "if_installed", "optional"]) }))
    .default({}),
  mcp: z.record(z.string(), lockMcpSchema).default({}),
  skills: z
    .record(
      z.string(),
      z.object({ path: z.string(), agent: agentIdSchema, filesCount: z.number().int().nonnegative(), fingerprint: fingerprintSchema }),
    )
    .default({}),
  hooks: z
    .record(z.string(), z.object({ event: z.string(), agent: agentIdSchema, files: stringList, fingerprint: fingerprintSchema }))
    .default({}),
  rules: z.record(z.string(), z.object({ agent: agentIdSchema, fingerprint: fingerprintSchema })).default({}),
  agentPermissions: z
    .record(z.string(), z.object({ sources: stringList, allow: stringList, deny: stringList, ask: stringList }))
    .default({}),
  instructions: z.object({
    strategy: z.enum(["cross-sync", "git-clean", "strict-hash"]),
    syncGroups: z
      .record(z.string(), z.object({ files: stringList, canonicalFingerprint: fingerprintSchema.optional() }))
      .default({}),
    files: z.record(z.string(), fingerprintSchema).optional(),
  }),
});

export type HarnessLockFile = z.output<typeof lockSchema>;
export type LockMcpEntry = HarnessLockFile["mcp"][string];

export function parseLockText(text: string, file = "harnesslock.lock"): HarnessLockFile {
  let raw: unknown;
  try {
    raw = parseYaml(text);
  } catch (error) {
    throw new ConfigValidationError(file, [`YAML syntax error: ${(error as Error).message}`]);
  }
  const result = lockSchema.safeParse(raw);
  if (!result.success) {
    throw new ConfigValidationError(file, formatZodIssues(result.error));
  }
  return result.data;
}

/** Recursively drops `undefined` values so serialized output is stable. */
function pruneUndefined(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(pruneUndefined);
  if (value !== null && typeof value === "object") {
    const out: Record<string, unknown> = {};
    for (const [key, inner] of Object.entries(value)) {
      if (inner !== undefined) out[key] = pruneUndefined(inner);
    }
    return out;
  }
  return value;
}

export function serializeLock(lock: HarnessLockFile): string {
  const header =
    "# harnesslock.lock — generated by `harnesslock lock`. Do not edit by hand.\n" +
    "# Secret values are never stored here: environment variables are recorded as `value: excluded`.\n";
  return header + stringifyYaml(pruneUndefined(lock), { lineWidth: 0, indent: 2 });
}
