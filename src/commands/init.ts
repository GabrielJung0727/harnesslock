import { promises as fs } from "node:fs";
import path from "node:path";
import semver from "semver";
import { stringify as stringifyYaml } from "yaml";
import { detectAgents, scanWorkspace } from "../adapters/index.js";
import { DEFAULT_POLICY } from "../schema/config-schema.js";
import { createPalette, header } from "../reporter/tui.js";
import { AGENT_IDS, AGENT_LABELS, VERSIONED_SOURCE_TYPES, type AgentDetection, type AgentId, type WorkspaceScan } from "../types/model.js";
import { findConfigFile, HarnessLockError, type CommandContext } from "./context.js";

const CANONICAL_INSTRUCTION_ORDER = ["CLAUDE.md", "AGENTS.md", ".claude/CLAUDE.md", "AGENTS.override.md"];

function slug(value: string): string {
  return value
    .replace(/([a-z])([A-Z])/g, "$1-$2")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

/** Derives a starting harnesslock.yaml from what is already committed in the repository. */
export function buildInitialConfig(scan: WorkspaceScan, detections: AgentDetection[]): Record<string, unknown> {
  const usedAgents = new Set<AgentId>();
  for (const result of scan.agents) {
    if (result.configFilesFound.length || result.instructionFiles.length || result.skills.length || result.rules.length) {
      usedAgents.add(result.agent);
    }
  }
  for (const detection of detections) if (detection.installed) usedAgents.add(detection.agent);

  const agents: Record<string, unknown> = {};
  for (const agent of AGENT_IDS) {
    if (!usedAgents.has(agent)) continue;
    const detection = detections.find((d) => d.agent === agent);
    const version = detection?.version ? semver.valid(semver.coerce(detection.version)) : null;
    agents[agent] = version ? { version: `>=${semver.major(version)}.${semver.minor(version)}.0`, presence: "if_installed" } : { presence: "if_installed" };
  }

  const instructionFiles = CANONICAL_INSTRUCTION_ORDER.filter((f) => scan.instructionFiles.includes(f));
  const syncGroups =
    instructionFiles.length >= 2
      ? [{ name: "core-agent-instructions", files: instructionFiles, enforce_identical: true }]
      : [];

  const mcp: Record<string, unknown> = {};
  for (const component of scan.mcps) {
    const entry: Record<string, unknown> = {};
    const source: Record<string, unknown> = { type: component.sourceType };
    if (component.sourceType === "docker" && component.packageName) source.image = component.packageName;
    else if (component.packageName) source.package = component.packageName;
    entry.source = source;
    if (VERSIONED_SOURCE_TYPES.includes(component.sourceType)) {
      const pinned = component.definitions.find((d) => d.isPinned)?.declaredVersion;
      const base = pinned ?? component.resolvedCacheVersion;
      const exact = base ? semver.valid(base) : null;
      if (exact) entry.version = `^${exact}`;
      else if (pinned) entry.version = pinned;
      entry.require_pinned = true;
    }
    const envKeys = Object.keys(component.requiredEnv);
    if (envKeys.length) entry.required_env = envKeys;
    if (component.permissions.length) entry.permissions = { allow: component.permissions, deny: ["admin:*"] };
    mcp[component.id] = entry;
  }

  const skills: Record<string, unknown> = {};
  for (const skill of scan.skills) {
    let name = skill.id;
    if (skills[name]) name = `${skill.agent}-${skill.id}`;
    skills[name] = { path: skill.path, required: true };
  }

  const hooks: Record<string, unknown> = {};
  const seen = new Set<string>();
  for (const hook of scan.hooks) {
    const key = `${hook.agent}:${hook.event}`;
    if (seen.has(key)) continue;
    seen.add(key);
    hooks[`${slug(hook.agent)}-${slug(hook.event)}`] = { event: hook.event, agent: hook.agent, required: true };
  }

  const config: Record<string, unknown> = {
    version: 1,
    agent_strategy: { require_at_least_one: true, default_presence: "if_installed" },
    agents,
    instructions: { strategy: "cross-sync", sync_groups: syncGroups },
    mcp,
    skills,
    hooks,
    policy: { ...DEFAULT_POLICY },
    user_scope: { allow_mcp: [], allow_hooks: false },
  };
  return config;
}

export function renderInitialConfig(config: Record<string, unknown>): string {
  return (
    "# harnesslock.yaml — desired state & policy for AI coding agents in this repository.\n" +
    "# Generated by `harnesslock init`. Review it, then run `npx harnesslock lock`.\n" +
    "# Docs: https://github.com/GabrielJung0727/harnesslock#configuration\n" +
    "# yaml-language-server: $schema=./node_modules/harnesslock/schemas/harnesslock.schema.json\n\n" +
    stringifyYaml(config, { lineWidth: 0 })
  );
}

export interface InitOptions {
  force?: boolean;
  dryRun?: boolean;
}

export async function runInit(ctx: CommandContext, options: InitOptions = {}): Promise<number> {
  const p = createPalette(ctx.color);
  const existing = await findConfigFile(ctx.root);
  if (existing && !options.force && !options.dryRun) {
    throw new HarnessLockError(`${path.basename(existing)} already exists. Use --force to overwrite it.`, 1);
  }
  const scan = await scanWorkspace(ctx);
  const detections = await detectAgents(ctx);
  const config = buildInitialConfig(scan, detections);
  const text = renderInitialConfig(config);

  if (options.dryRun) {
    ctx.stdout(text);
    return 0;
  }
  await fs.writeFile(path.join(ctx.root, "harnesslock.yaml"), text, "utf8");

  const agents = Object.keys(config.agents as object) as AgentId[];
  const out = [
    header(p, "Init"),
    "",
    `  ${p.ok("✓")} Created harnesslock.yaml`,
    `    ${p.dim(`agents: ${agents.map((a) => AGENT_LABELS[a]).join(", ") || "none detected"}`)}`,
    `    ${p.dim(`${scan.mcps.length} MCP servers · ${scan.skills.length} skills · ${scan.hooks.length} hooks · ${scan.rules.length} rules`)}`,
  ];
  for (const issue of scan.parseErrors) out.push(`  ${p.warn("⚠")} could not parse ${issue.file}: ${issue.message}`);
  out.push("", p.bold("Next steps:"), `  1. Review harnesslock.yaml`, `  2. ${p.c.cyan("npx harnesslock lock")}`, `  3. ${p.c.cyan("npx harnesslock verify")}`);
  ctx.stdout(`${out.join("\n")}\n`);
  return 0;
}
